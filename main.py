# ==========================================================
# NEW: GEMINI RESPONSE GENERATOR - POC
# ==========================================================
#
# Purpose:
#
# Generate:
#     1. A concise natural-language answer
#     2. Exactly 3 follow-up questions
#
# IMPORTANT:
#
# We intentionally DO NOT send the actual Snowflake rows.
#
# Gemini receives only:
#
#     - User question
#     - Cortex Analyst interpretation
#     - Returned table schema
#
# Actual result rows remain inside the backend and are
# returned to Power BI separately.
#
# Future:
#
# This entire function can be replaced with Snowflake
# AI_COMPLETE after approval.
#
# ==========================================================

def generate_ai_response(
    user_question: str,
    analyst_answer: str,
    table_schema: list
):

    """
    Generate a concise answer and exactly 3 follow-up
    questions using Gemini.

    Only the table schema is sent to Gemini.
    Actual Snowflake result data is NOT sent.
    """

    # ------------------------------------------------------
    # Gemini model
    # ------------------------------------------------------

    model = os.getenv(
        "GEMINI_MODEL",
        "gemini-2.5-flash"
    )


    # ------------------------------------------------------
    # Prompt
    # ------------------------------------------------------

    prompt = f"""
You are a business analytics assistant inside a Power BI report.

The user asked:

{user_question}

Cortex Analyst interpreted the user's request as:

{analyst_answer}

The SQL query generated by Cortex Analyst returned a table
with the following schema:

{json.dumps(table_schema, indent=2)}

Important restrictions:

- You do NOT have access to the actual rows or values.
- Do NOT invent numbers.
- Do NOT invent brands, retailers, companies, dates, or metrics
  that are not present in the information provided.
- Base your response only on the user's question, Cortex Analyst's
  interpretation, and the returned table schema.

Your responsibilities:

1. Provide a concise answer to the user's question.
2. Since actual data values are not available to you, do not
   make claims about specific values or rankings.
3. Generate exactly 3 useful follow-up questions.
4. Follow-up questions should be relevant to the user's original
   question and the available table schema.
5. Prefer analytical follow-ups involving the available fields,
   such as comparisons, trends, rankings, year-over-year analysis,
   filtering, or breakdowns where appropriate.
6. Do not ask generic questions such as:
   "Would you like more information?"
7. Do not include SQL.
8. Return valid JSON only.

Return exactly this structure:

{{
    "answer": "A concise answer based only on the supplied information",
    "follow_up_questions": [
        "Question 1",
        "Question 2",
        "Question 3"
    ]
}}
"""


    # ------------------------------------------------------
    # Call Gemini
    # ------------------------------------------------------

    try:

        response = gemini_client.models.generate_content(

            model=model,

            contents=prompt,

            config={
                "response_mime_type": "application/json"
            }
        )


        # --------------------------------------------------
        # Extract Gemini response
        # --------------------------------------------------

        result_text = response.text


        # --------------------------------------------------
        # Parse JSON
        # --------------------------------------------------

        result = json.loads(
            result_text
        )


        follow_up_questions = result.get(
            "follow_up_questions",
            []
        )


        # --------------------------------------------------
        # Make sure we never return more than 3
        # --------------------------------------------------

        follow_up_questions = (
            follow_up_questions[:3]
        )


        return {

            "answer":
                result.get(
                    "answer",
                    ""
                ),

            "follow_up_questions":
                follow_up_questions

        }


    except Exception as e:

        raise Exception(
            f"Gemini failed: {str(e)}"
        )


