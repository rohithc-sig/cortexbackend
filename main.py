@app.post("/chat")
def chat(request: ChatRequest):

    # ======================================================
    # EXISTING CORTEX ANALYST LOGIC
    # ======================================================


    # ------------------------------------------------------
    # 1. Append Power BI context/slicers if available
    # ------------------------------------------------------

    user_query = request.question


    if (
        request.pbi_context
        and request.pbi_context.get("categories")
    ):

        filters = []


        for cat in request.pbi_context["categories"]:

            col = (

                cat.get("columnName")

                or

                cat.get("column")

            )


            vals = (

                cat.get("values")

                or

                cat.get(
                    "activeValues",
                    []
                )

            )


            if col and vals:

                formatted_vals = ", ".join(

                    [
                        f"'{v}'"
                        for v in vals
                    ]

                )


                filters.append(

                    f"{col} IN ({formatted_vals})"

                )


        if filters:

            user_query += (

                f" (Context filters: "

                f"{'; '.join(filters)})"

            )


    # ------------------------------------------------------
    # 2. Construct Cortex Analyst REST Payload
    # ------------------------------------------------------

    account = os.getenv(
        "SNOWFLAKE_ACCOUNT"
    )


    # Clean host URL if user provides account identifier
    # or full host.

    if "snowflakecomputing.com" in account:

        host_url = (
            f"https://{account}"
        )

    else:

        host_url = (

            f"https://"
            f"{account}"
            f".snowflakecomputing.com"

        )


    url = (

        f"{host_url}"
        f"/api/v2/cortex/analyst/message"

    )


    payload = {

        "messages": [

            {

                "role":
                    "user",

                "content": [

                    {

                        "type":
                            "text",

                        "text":
                            user_query

                    }

                ]

            }

        ],

        "semantic_view": os.getenv(

            "SNOWFLAKE_SEMANTIC_VIEW",

            "CPG.PUBLIC.SALES_SEMANTIC"

        )

    }


    headers = {

        "Authorization":
            f"Bearer "
            f"{os.getenv('SNOWFLAKE_PAT')}",

        "Content-Type":
            "application/json",

        "X-Snowflake-Authorization-Token-Type":
            "PROGRAMMATIC_ACCESS_TOKEN"

    }


    # ------------------------------------------------------
    # 3. Call Snowflake Cortex Analyst REST API
    # ------------------------------------------------------

    try:

        response = requests.post(

            url,

            json=payload,

            headers=headers,

            timeout=60

        )


    except Exception as e:

        raise HTTPException(

            status_code=500,

            detail=(

                "Failed to reach Cortex API: "

                f"{str(e)}"

            )

        )


    if response.status_code != 200:

        try:

            error_detail = (
                response.json()
            )

        except Exception:

            error_detail = (
                response.text
            )


        raise HTTPException(

            status_code=
                response.status_code,

            detail=
                error_detail

        )


    data = response.json()


    # ------------------------------------------------------
    # Parse Cortex Analyst response
    # ------------------------------------------------------

    answer_text = ""

    generated_sql = ""


    for item in data.get(

        "message",

        {}

    ).get(

        "content",

        []

    ):

        if item.get("type") == "text":

            answer_text += (

                item.get(
                    "text",
                    ""
                )

                + "\n"

            )


        elif item.get("type") == "sql":

            generated_sql = (

                item.get(
                    "statement",
                    ""
                )

            )


    # ------------------------------------------------------
    # 4. Execute Generated SQL
    # ------------------------------------------------------

    columns = []

    rows = []


    # ======================================================
    # NEW: TABLE SCHEMA FOR GEMINI - POC
    # ======================================================
    #
    # Example:
    #
    # [
    #     {
    #         "name": "BRAND_NAME",
    #         "type": "VARCHAR"
    #     },
    #     {
    #         "name": "DOLLAR_SALES",
    #         "type": "NUMBER"
    #     }
    # ]
    #
    # Only this schema will be sent to Gemini.
    # Actual rows will NOT be sent.
    #
    # ======================================================

    table_schema = []


    # ======================================================
    # END NEW: TABLE SCHEMA FOR GEMINI - POC
    # ======================================================


    if generated_sql:

        try:

            conn = get_connection()

            cursor = conn.cursor()


            cursor.execute(
                generated_sql
            )


            # ------------------------------------------------
            # Extract column headers
            # ------------------------------------------------

            if cursor.description:

                columns = [

                    desc[0]

                    for desc
                    in cursor.description

                ]


                # ==================================================
                # NEW: EXTRACT ONLY TABLE SCHEMA - POC
                # ==================================================
                #
                # cursor.description contains metadata about the
                # returned result columns.
                #
                # We use:
                #
                #     desc[0] -> column name
                #     desc[1] -> Snowflake type
                #
                # We intentionally do NOT send row values.
                #
                # ==================================================

                for desc in cursor.description:

                    column_name = desc[0]


                    column_type = (

                        str(desc[1])

                        if desc[1] is not None

                        else "UNKNOWN"

                    )


                    table_schema.append(

                        {

                            "name":
                                column_name,

                            "type":
                                column_type

                        }

                    )


                # ==================================================
                # END NEW: EXTRACT ONLY TABLE SCHEMA - POC
                # ==================================================


                # ------------------------------------------------
                # Existing behavior:
                # Fetch rows for Power BI table rendering.
                #
                # IMPORTANT:
                # These rows are still returned to Power BI.
                # They are NOT passed to Gemini.
                # ------------------------------------------------

                raw_rows = (
                    cursor.fetchall()
                )


                for row in raw_rows:

                    row_dict = {}


                    for idx, col_name in enumerate(
                        columns
                    ):

                        row_dict[col_name] = (

                            str(row[idx])

                            if row[idx] is not None

                            else ""

                        )


                    rows.append(
                        row_dict
                    )


        except Exception as sql_err:

            answer_text += (

                "\n\n"

                f"*(Note: Generated SQL failed "
                f"to execute: {str(sql_err)})*"

            )


        finally:

            if "cursor" in locals():

                cursor.close()


            if "conn" in locals():

                conn.close()


    # ======================================================
    # NEW: GEMINI RESPONSE GENERATION - POC
    # ======================================================
    #
    # At this point we have:
    #
    #     user question
    #     Cortex Analyst answer
    #     generated SQL
    #     table schema
    #     rows
    #
    # BUT:
    #
    # We send ONLY:
    #
    #     user question
    #     Cortex Analyst answer
    #     table schema
    #
    # to Gemini.
    #
    # The actual rows remain inside your backend and are
    # returned to Power BI as before.
    #
    # ======================================================

    ai_answer = (
        answer_text.strip()
    )

    follow_up_questions = []


    try:

        ai_result = generate_ai_response(

            user_question=
                request.question,

            analyst_answer=
                answer_text.strip(),

            table_schema=
                table_schema

        )


        ai_answer = ai_result.get(

            "answer",

            answer_text.strip()

        )


        follow_up_questions = (

            ai_result.get(

                "follow_up_questions",

                []

            )

        )


        # Safety check:
        # maximum 3 questions.

        follow_up_questions = (

            follow_up_questions[:3]

        )


    except Exception as llm_err:

        print(
            f"Gemini error: {llm_err}"
        )

        raise HTTPException(
            status_code=500,
            detail=f"Gemini failed: {str(llm_err)}"
        )


    # ======================================================
    # END NEW: GEMINI RESPONSE GENERATION - POC
    # ======================================================


    # ======================================================
    # FINAL RESPONSE TO POWER BI
    # ======================================================

    return {

        "answer":
            ai_answer,

        "follow_up_questions":
            follow_up_questions,

        "sql":
            generated_sql,

        "columns":
            columns,

        "rows":
            rows,

        "request_id":
            data.get(
                "request_id"
            ),

        "warnings":
            data.get(
                "warnings",
                []
            )

    }